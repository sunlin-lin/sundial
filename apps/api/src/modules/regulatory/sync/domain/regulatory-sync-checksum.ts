/**
 * 政府原始內容的指紋（零 IO 純函式，§0.1）。
 *
 * 用途只有一個：判斷這一次抓到的東西與上一版是不是同一份（相同即 `status_code=4 無異動`，
 * 計畫 §7.1）。沒有它的話，每天的排程都會寫進一個內容完全相同的新版本，
 * 於是 `regulatory_dataset_versions` 每年多 365 列同日生效的版本——直接餵給計畫 §3.2 的排序問題。
 *
 * ## SHA-256，且比對的是**原始內容**而不是解析結果
 *
 * 比對解析結果會漏掉「政府改了我們還沒解析的欄位」，而那正是下一次要重跑解析器時最需要的資訊；
 * 而且解析器一改，全部資料集的 checksum 都會變一次，於是每一個資料集都被寫進一個新版本，
 * 內容卻與舊版逐字相同。原始內容不受我們這一側的改動影響。
 *
 * **這不是安全用途，是變更偵測**，因此不需要 HMAC 或加鹽——沒有攻擊者能從我們這裡選擇輸入。
 * 選 SHA-256 而不是更短的雜湊，是因為 `checksum` 欄位是 `varchar(128)`（容得下 SHA-512），
 * 而碰撞在這裡的後果是「政府改了內容但我們認為沒改」——一個安靜的、不會有任何錯誤的結果。
 */
import { createHash } from 'node:crypto'

/**
 * @param rawText 政府資源的原始內容（就是要寫進 `raw_data` 的那一串，未經任何前處理）。
 *   **不做 trim、不做正規化**：那些都是「兩份不同的位元組被算成同一份」的來源。
 */
export const toContentChecksum = (rawText: string): string =>
  createHash('sha256').update(rawText, 'utf8').digest('hex')
