/**
 * 動作碼的型別（計畫 §4.1）。
 *
 * ## 由模組路徑推導，不另編一套
 *
 * ```text
 * employees.main.update                 誰改了員工
 * company-users.roles.assign            誰指派了角色
 * sessions.main.refresh-token-reuse     偵測到憑證重用（無端點，由驗證器產生）
 * ```
 *
 * 形狀一律是 `<大目錄>.<次目錄>.<動作>`，三段、全部 kebab-case——與 `shared/path-code.ts` 由路由路徑
 * 推出的 `cmd` 與權限碼是**同一組字串**。這是同一個機制的第三次使用（權限碼 §5.2.2、`cmd` §1.3、
 * 現在是動作碼），附帶好處是「誰被授權做這件事」與「誰真的做了這件事」可以直接對起來。
 *
 * 另編一套整數代碼（`1=建立員工、2=修改員工…`）的代價是**每加一支端點就要做一次命名判斷**，
 * 而那沒有標準答案：同一件事在不同人手上會變成 `employee_update`／`update_employee`／`EMPLOYEE_MODIFY`，
 * 每一個都「有道理」。由路徑推導則連判斷都不需要——動作在哪個目錄，前兩段就是什麼。
 *
 * **沒有端點的事件**（排程、憑證驗證器偵測）沿用同一形狀，第三段是事件名。
 * 它們不是端點，但一樣屬於某個模組，因此一樣有前兩段。
 *
 * ## 為什麼本檔只有型別
 *
 * 不在這裡放「由路徑推導動作碼」的函式：`shared/path-code.ts` 已經有那個轉換，
 * 而它收的是**路由路徑**。稽核的動作碼有一部分沒有對應的路由（上面第三個例子），
 * 硬要共用一支函式就得為「沒有路徑的事件」發明一個假路徑，那比直接寫下字面值更容易寫錯。
 */

/**
 * 動作碼。
 *
 * 用樣板字面值型別而不是 `string`：**`string` 不可指派給它**，因此呼叫端只能寫字面值
 * （或明確地轉型，那會在 review 上看得見），一個少了段數的 `'update'` 會當場是型別錯誤。
 *
 * 型別能保證的只有「有三段」；kebab-case 與「前兩段必須對得上實際的模組目錄」保證不了
 * ——那是掃描腳本的守備範圍（§8 的路徑／代碼一致性檢查），寫在型別上只會得到一個
 * 看起來很嚴格、實際上仍然放行 `employees.Main.Update` 的假保證。
 */
export type AuditAction = `${string}.${string}.${string}`
