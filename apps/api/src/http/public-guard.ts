/**
 * 公開群組的憑證驗證器：**明確指定為「不驗」**（§1.9.1、§1.9.2）。
 *
 * 這個 plugin 什麼都不做，而它必須存在。理由是 §1.9.2 那條看起來只是形式要求的規則：
 * **「忘了加驗證」與「刻意公開」必須長得不一樣。**
 * 兩者長得一樣時，一個沉默的安全漏洞在程式碼上與正常程式碼**逐字相同**——沒有多一行、
 * 沒有少一行，review 看不出來，只能逐支去問當初寫的人，而問到的答案還是「應該有吧」。
 *
 * 掛上這一行之後，「這一組端點不需要身分」是一個**看得見、可以在 PR 上被要求說明理由**的宣告；
 * 而 §1.9.1 要求的三元組（憑證來源, 憑證驗證器, 續期行為）在公開群組上也就填得滿：
 *
 * | 元素 | 公開群組的值 |
 * |---|---|
 * | 憑證來源 | **無**——呼叫這些端點的時候使用者手上還沒有（或已經沒有）憑證 |
 * | 憑證驗證器 | 本 plugin：明確的「不驗」 |
 * | 續期行為 | **不續期**。沒有票可以續；`expiresIn` 因此是 `null`（§1.3），除非端點自己發了一張新票 |
 *
 * **登入端點落在這裡不是特例**（§1.9.0）：它與其他公開端點的唯一差別是它會觸發發證元件，
 * 而那是端點自己的業務，不是群組的屬性。這一節不開任何豁免區——開了之後
 * `report`／`export`／`dashboard` 會逐一援引它，而它撐不過第二種入口。
 */
import { Elysia } from 'elysia'

export const publicGuard = new Elysia({ name: 'public-guard' })
