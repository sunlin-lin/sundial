/**
 * 權限判斷的原語（前端規範 §4.1、§0.1 的 `shared/permission/`）。
 *
 * ## 為什麼這裡是純函式，而不是一個「知道目前是誰」的模組
 *
 * §0.11 明文禁止 `shared/` import `stores/`。這不是形式上的分層潔癖——`shared/` 一旦讀得到
 * 登入狀態，「這支函式在哪些情境下能用」就變成不可回答的問題（登入前呼叫會拿到什麼？型別上完全
 * 看不出來）。因此本檔**不吃任何 ambient state**：權限碼集合由呼叫端傳進來。
 *
 * 兩件事因此同時成立：
 *
 * - 「目前使用者有哪些權限碼」由 `stores/auth.ts` 持有（它是唯一有生命週期的那一層，§2.1），
 *   並在那裡把本檔綁成 `can(code)` 對外提供給頁面與路由守衛。
 * - 「有沒有這個權限碼」是一個可以逐格測的純函式，測試不需要 Pinia、不需要 app context（§8.1）。
 *
 * ## 為什麼只有 `can` 的原語，沒有 `canAny` / `canAll` / `scope`
 *
 * §4.1 列的原語是四支，但**這一輪四支裡只有一支有消費者**。三支沒有呼叫端的函式不是「先準備好」，
 * 它們是三條永遠不會被執行的規則（通用規範 §7.1：永遠是綠的規則比沒有規則更糟）——
 * 它們唯一的執行者會是自己的測試，於是測試綠燈證明的只有「這三支函式本身沒寫錯」，
 * 而沒有任何畫面因此更正確。
 *
 * `scope(resource)` 另外還缺一個更基本的東西：**後端沒有資源層級的範圍模型**。法規資料不分公司
 *（計畫 03 §2.1），這一輪也沒有第二種資源需要「看得到哪些範圍」。現在寫出來的 `scope` 只能是
 * 一個猜出來的簽章，而它會在真正需要範圍判斷的那一天被整支重寫——先寫的那一版唯一的作用是
 * 讓人以為這件事已經想過了。
 *
 * 三支各自的補法都是一行（`codes.some(...)` / `codes.every(...)`），要加的那一天，
 * 它的形狀會由真正的呼叫端決定，而不是由想像決定（§1.5 的同一條理由）。
 */
import type { PermissionCode } from './permission-code.ts'

/**
 * 這組權限碼裡有沒有 `code`。
 *
 * @param granted 使用者實際擁有的權限碼。型別是 `readonly string[]` 而不是
 *   `readonly PermissionCode[]`：它直接來自後端（`sessions/main/context` 的 `permissionCodes`），
 *   而後端會回**這個成員在這家公司實際擁有的全部權限碼**——那一份遠多於前端宣告的五個。
 *   收窄成 `PermissionCode[]` 就得先過濾，而過濾掉的東西不會有任何症狀，只會讓某些判斷
 *   在權限碼還沒被前端宣告時安靜地變成 false。
 * @param code 要判斷的權限碼。**這一側才是型別化的**（§4.1）：打錯字是編譯錯誤，
 *   而不是一個永遠回 false 的判斷。
 */
export const hasPermission = (granted: readonly string[], code: PermissionCode): boolean =>
  granted.includes(code)
