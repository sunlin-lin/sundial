/**
 * 「這一格沒有值」在畫面上長什麼樣（§9.2 的格式化統一在本目錄）。
 *
 * **為什麼是一個共用常數，而不是各個 format 函式各寫一個 `'—'`。**
 * 空值的呈現是一個**決定**，不是一個字元：全站統一之後，使用者掃過一張表就能分辨
 * 「這格是空的」與「這格有值但很短」；各寫一份的話，第一次出現 `'-'`（半形連字號）
 * 與 `'—'`（破折號）混用時沒有任何東西會紅，而兩者在表格裡看起來就是不同的兩種狀態。
 *
 * **它不是「不適用」。** 計畫 §4.1 明文區分這兩件事：人工維護的資料集**永遠不會有同步紀錄**，
 * 那一格要顯示「不適用」而不是空白——因為空白會被讀成「同步壞了」或「還沒跑過」，
 * 而那是規格，不是故障。「不適用」是頁面依資料語意做的判斷（`.view.ts` 的職責，§1.3 的 (1)），
 * format 層看到的只是一個 `null`，分辨不出這個 `null` 是「沒跑過」還是「不會跑」。
 * 因此本常數只表達「沒有值」這一件事，**頁面不得拿它去表達「不適用」**。
 */
