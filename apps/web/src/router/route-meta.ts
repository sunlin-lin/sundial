/**
 * 路由 meta 的型別擴充。
 *
 * 兩個欄位，兩條相反方向的預設值——都是刻意的：
 *
 * - `isPublic`：守衛的預設是「需要登入」，公開頁面必須**明寫**出來。與後端「公開端點必須放在
 *   具名的公開群組」是同一條規則的兩面（後端規範 §1.9.2）：「沒有標記」與「刻意公開」若長得
 *   一樣，一個沉默的安全漏洞在程式碼上與正常程式碼逐字相同，review 看不出來。
 * - `permission`：預設是「不需要任何權限碼」。這一側不能反過來要求明寫——首頁那種
 *   「登入了就看得到」的頁面本來就沒有對應的權限碼可以填，逼它填會逼出一個假的權限碼。
 */
import 'vue-router'
import type { PermissionCode } from '../shared/permission/permission-code.ts'

declare module 'vue-router' {
  interface RouteMeta {
    /** 明寫 `true` 才是公開路由；未標記一律視為需要登入。 */
    isPublic?: boolean

    /**
     * 進入這一頁所需的權限碼（§4.1、§4.3）。
     *
     * **型別是聯集不是 `string`**：打錯一個字母的後果是「這一頁永遠進不去」，
     * 而那與「這個人真的沒有權限」在畫面上逐字相同，不會有人回報。
     *
     * 單一權限碼而不是陣列：這一輪每一頁的入口都由**一支端點**決定（進得去卻什麼都載不出來
     * 的頁面沒有意義），而一個「任一即可」還是「全部都要」的陣列會逼出一個沒有人需要的語意選擇。
     * 真的出現需要兩個權限碼的頁面時再改型別，那時候會有一個真實案例決定它是 any 還是 all。
     */
    permission?: PermissionCode
  }
}
